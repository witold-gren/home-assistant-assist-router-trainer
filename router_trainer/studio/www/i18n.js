/** A text of the studio (else of the training panel, else the key), with {name} filled in. */
export function translate(language, key, values = {}, panel = {}) {
  const lang = language === "pl" ? "pl" : "en";
  const text = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? panel?.[key] ?? key;
  return String(text).replace(/\{(\w+)\}/g, (_, name) => (values[name] ?? `{${name}}`));
}

export function hasStudioText(key) {
  return key in STRINGS.en;
}

export const STUDIO_STRINGS = STRINGS;
